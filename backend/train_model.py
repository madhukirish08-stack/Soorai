"""
Belt RUL Model Trainer
======================
Trains an XGBoost regressor on any belt dataset.
XGBoost only: on held-out belts it beat the former XGBoost + Random Forest ensemble
(R² 0.920 vs 0.895), so the RF was removed - don't re-add it without re-checking that.

The raw CSV is first converted to the canonical schema (canonical_schema.json) via an
approved column mapping (schema_mapper.py). The feature set is whatever canonical /
extra numeric columns the mapped data actually contains - it is NOT a fixed list.
Target: rul_hours - measured if present, otherwise generated by schema_mapper.derive_rul().

Usage:
    python train_model.py --csv path/to/data.csv [--mapping path/to/data.csv.mapping.json]
"""

import argparse
import os
import json
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split, GroupShuffleSplit
from sklearn.metrics import mean_absolute_error, r2_score, mean_squared_error
import xgboost as xgb

import schema_mapper as sm

TARGET_COL = "rul_hours"
# Columns with less coverage than this are dropped instead of imputed.
MIN_FEATURE_COVERAGE = 0.5


def select_feature_cols(df: pd.DataFrame, schema: dict) -> list:
    """Canonical features in schema order, then extra customer features."""
    canonical = sm.fields_by_role(schema, "feature", "degradation", "time")
    extras = sorted(c for c in df.columns if c.startswith(sm.EXTRA_PREFIX))
    return [
        c for c in canonical + extras
        if c in df.columns and df[c].notna().mean() >= MIN_FEATURE_COVERAGE
    ]


def load_and_prepare(csv_path: str, mapping: list = None):
    raw = pd.read_csv(csv_path)
    schema = sm.load_canonical()
    df = sm.apply_mapping(raw, mapping or sm.identity_mapping(raw.columns))
    df, rul_info = sm.derive_rul(df)

    feature_cols = select_feature_cols(df, schema)
    if not feature_cols:
        raise ValueError("No usable feature columns after mapping.")
    df = df[df[TARGET_COL].notna()]
    X = df[feature_cols].copy()
    # Median-impute sparse gaps so training sees the same value /predict substitutes for a
    # missing input (the training median).
    X = X.fillna(X.median(numeric_only=True))
    y = df[TARGET_COL]
    return X, y, df, rul_info


def compute_feature_stats(X: pd.DataFrame) -> dict:
    stats = {}
    for col in X.columns:
        stats[col] = {
            "min": float(X[col].min()),
            "max": float(X[col].max()),
            "mean": float(X[col].mean()),
            "median": float(X[col].median()),
            "std": float(X[col].std()),
            "p25": float(X[col].quantile(0.25)),
            "p75": float(X[col].quantile(0.75)),
        }
    return stats


def train(csv_path: str, output_dir: str = "models_v2", mapping: list = None):
    os.makedirs(output_dir, exist_ok=True)

    print(f"Loading data from: {csv_path}")
    X, y, df, rul_info = load_and_prepare(csv_path, mapping)
    feature_cols = list(X.columns)
    print(f"Features ({len(feature_cols)}): {feature_cols}")
    print(f"RUL source: {rul_info['message']}")
    print(f"Training samples: {len(X):,}  |  RUL range: {y.min():.0f} - {y.max():.0f} hrs")

    # Split by BELT, not by row: a belt's readings are near-duplicates of each other, so a
    # row split puts the same belt in train and test and inflates R². Do not revert to a
    # plain row split - the metrics must describe performance on belts the model never saw.
    if "belt_id" in df.columns and df["belt_id"].nunique() >= 5:
        gss = GroupShuffleSplit(n_splits=1, test_size=0.20, random_state=42)
        train_idx, test_idx = next(gss.split(X, y, groups=df["belt_id"]))
        X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
        y_train, y_test = y.iloc[train_idx], y.iloc[test_idx]
        split = "by_belt"
    else:
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=0.20, random_state=42
        )
        split = "by_row"
    print(f"Test split: {split} ({len(X_test):,} test rows)")

    # XGBoost
    print("\nTraining XGBoost Regressor...")
    xgb_model = xgb.XGBRegressor(
        n_estimators=600,
        max_depth=7,
        learning_rate=0.05,
        subsample=0.85,
        colsample_bytree=0.85,
        min_child_weight=3,
        reg_alpha=0.1,
        reg_lambda=1.0,
        random_state=42,
        n_jobs=-1,
    )
    xgb_model.fit(X_train, y_train, eval_set=[(X_test, y_test)], verbose=100)

    y_pred_xgb = xgb_model.predict(X_test)

    def get_metrics(y_true, y_pred, label):
        mae  = mean_absolute_error(y_true, y_pred)
        rmse = float(np.sqrt(mean_squared_error(y_true, y_pred)))
        r2   = r2_score(y_true, y_pred)
        print(f"  [{label}]  MAE={mae:,.0f} hrs  RMSE={rmse:,.0f} hrs  R2={r2:.4f}")
        return {"mae_hours": round(float(mae), 1), "rmse_hours": round(float(rmse), 1), "r2_score": round(float(r2), 4)}

    print("\n-- Test-set Metrics --")
    xgb_metrics = get_metrics(y_test, y_pred_xgb, "XGBoost")

    feat_imp = dict(zip(feature_cols, [float(x) for x in xgb_model.feature_importances_]))
    feat_imp = dict(sorted(feat_imp.items(), key=lambda x: x[1], reverse=True))

    feature_stats = compute_feature_stats(X)

    payload = {
        "xgb_model": xgb_model,
        "training_rows": int(len(X)),
        "feature_cols": feature_cols,
        "target_col": TARGET_COL,
        "feature_stats": feature_stats,
        "rul_source": rul_info,
        "mapping": mapping,
        "test_split": split,
        "metrics": {"xgboost": xgb_metrics},
        "feature_importance": feat_imp,
        "y_max": float(y.max()),
        "y_mean": float(y.mean()),
    }
    model_path = os.path.join(output_dir, "rul_model.pkl")
    joblib.dump(payload, model_path)

    metadata = {
        "training_rows": int(len(X)),
        "dataset": os.path.basename(csv_path),
        "feature_cols": feature_cols,
        "target_col": TARGET_COL,
        "feature_stats": feature_stats,
        "rul_source": rul_info,
        "mapping": mapping,
        "test_split": split,
        "feature_importance": feat_imp,
        "metrics": payload["metrics"],
        "y_max": float(y.max()),
        "y_mean": float(y.mean()),
    }
    meta_path = os.path.join(output_dir, "model_metadata.json")
    with open(meta_path, "w") as f:
        json.dump(metadata, f, indent=2)

    print(f"\n[OK] Model saved   : {model_path}")
    print(f"[OK] Metadata saved: {meta_path}")
    return payload


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train Belt RUL Model")
    parser.add_argument("--csv",    default="../data/belt_rul_training_data.csv")
    parser.add_argument("--output", default="../models_v2")
    parser.add_argument("--mapping", default=None, help="Approved *.mapping.json (omit for canonical-named CSVs)")
    args = parser.parse_args()
    mapping = None
    if args.mapping:
        with open(args.mapping, encoding="utf-8") as f:
            mapping = json.load(f)["mapping"]
    train(args.csv, args.output, mapping)
